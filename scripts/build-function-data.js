// Copies the two data files the server functions need into a plain JavaScript module.
// Why: Cloudflare Pages bundles `functions/` with a tool that cannot read
// `import x from 'file.json' with { type: 'json' }`, which Node needs. A plain module works in both.
// Run by `npm run build`; the result is committed, and a test fails if it is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const at = (p) => fileURLToPath(new URL(`../${p}`, import.meta.url));
export const OUT = at('functions/_shared/data.generated.js');

export function render() {
  const facilities = JSON.parse(readFileSync(at('src/data/facilities.json'), 'utf8'));
  const roads = JSON.parse(readFileSync(at('src/data/roads.json'), 'utf8'));
  return '// Generated by scripts/build-function-data.js from src/data/facilities.json and src/data/roads.json. Do not edit by hand.\n'
    + `export const facilityRecords = ${JSON.stringify(facilities)};\n`
    + `export const roadData = ${JSON.stringify(roads)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log('wrote functions/_shared/data.generated.js');
}
